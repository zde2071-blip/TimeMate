   await page.locator('.guide-close-x').click();
   assert.equal(await page.locator('#calendar-url').inputValue(),appleUrl);
   await page.locator('#calendar-profile-dialog').getByRole('button',{name:'取消',exact:true}).click();
   await page.getByRole('button',{name:'设置 Outlook 日历',exact:true}).getByText('待确认',{exact:true}).waitFor();
   await page.reload();await page.locator('#settings-nav-calendar').click();await page.locator('#calendar-profile-list').waitFor();
   await page.getByRole('button',{name:'设置 Apple 日历',exact:true}).getByText('✓ 已订阅',{exact:true}).waitFor();
   await page.getByRole('button',{name:'设置 Outlook 日历',exact:true}).click();
   assert.equal(await page.locator('#calendar_provider').isDisabled(),true);
   assert.equal(await page.locator('#calendar_provider').inputValue(),'outlook');
   await page.locator('#calendar-connect').click();await page.locator('#calendar-profile-dialog').waitFor({state:'hidden'});
   await page.getByRole('button',{name:'设置 Outlook 日历',exact:true}).getByText('✓ 已订阅',{exact:true}).waitFor();
