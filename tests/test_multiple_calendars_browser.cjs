   await page.route('**/api/calendar/settings',route=>route.fulfill({status:503,json:{error:'fixture confirmation unavailable'}}),{times:1});
   await page.locator('#calendar-connect').click();
   await page.locator('#calendar-feedback').getByText('fixture confirmation unavailable',{exact:true}).waitFor();
