const assert = require('node:assert/strict'), vm = require('node:vm');
const context = vm.createContext({});
vm.runInContext(require('./ui_source').functions('localDateKey', 'importantItemDate', 'scheduleEnd', 'scheduleEnded', 'scheduleInProgress', 'importantOccursOn', 'compareImportantItems', 'importantEventTime', 'deadlineRemainingMs'), context);
const {scheduleEnded, scheduleInProgress, importantOccursOn, importantItemDate, importantEventTime} = context;
const now = new Date('2026-10-26T12:00:00');
const schedule = (start, end = '', rest = {}) => ({kind: 'schedule', event: {start, end, ...rest}});
assert.equal(scheduleEnded(schedule('2026-10-25T10:00', '2026-10-25T11:00'), now), true);
assert.equal(scheduleEnded(schedule('2026-10-26T10:00'), now), false, 'missing end stays active through its start day');
assert.equal(scheduleEnded(schedule('2026-10-25T10:00'), now), true, 'unknown end does not remain active forever');
const ongoing = schedule('2026-10-24T10:00', '2026-10-28T11:00');
assert.equal(scheduleInProgress(ongoing, now), true);
assert.equal(scheduleEnded(ongoing, now), false);
for (const day of ['24', '25', '26', '27', '28']) assert.equal(importantOccursOn(ongoing, '2026-10-' + day), true);
assert.equal(importantOccursOn(ongoing, '2026-10-29'), false);
const midnight = schedule('2026-10-25T23:00', '2026-10-26T00:00');
assert.equal(importantOccursOn(midnight, '2026-10-26'), false, 'exclusive midnight ends do not add another day');
const allDay = schedule('2026-10-24T00:00', '2026-10-27T00:00', {allDay: true});
assert.equal(scheduleEnded(allDay, now), false);
assert.equal(importantOccursOn(allDay, '2026-10-26'), true);
assert.equal(importantOccursOn(allDay, '2026-10-27'), false, 'ICS all-day end remains exclusive');
assert.equal(importantOccursOn(schedule('2026-10-24T00:00:00Z', '2026-10-27T00:00:00Z', {allDay: true}), '2026-10-27'), false, 'all-day dates are civil days even with an offset');
const dateOnly = schedule('2026-10-24', '2026-10-26', {allDay: true});
assert.equal(scheduleEnded(dateOnly, now), false, 'date-only end includes the whole last day');
assert.equal(importantOccursOn(dateOnly, '2026-10-26'), true);
assert.equal(scheduleInProgress(schedule('2026-10-26', '', {allDay: true}), new Date('2026-10-26T00:01')), true);
const deadline = {kind: 'deadline', event: {start: '2026-10-20T12:00'}};
assert.equal(scheduleEnded(deadline, now), false, 'unfinished overdue deadlines never become ended schedules');
assert.equal(importantOccursOn(deadline, '2026-10-20'), true);
assert.equal(importantOccursOn(deadline, '2026-10-26'), false);
const zoned = schedule('2026-10-25T23:30:00Z', '2026-10-26T01:00:00Z');
assert.equal(importantItemDate(zoned), context.localDateKey(new Date(zoned.event.start)), 'offset timestamps are shown on their local day');
assert.equal(importantEventTime(deadline, true).includes('（截止）'), true);
assert.equal(importantEventTime(allDay).includes('10/24–10/26'), true, 'cross-day all-day range remains visible');
assert.equal(context.deadlineRemainingMs({event: {start: '2026-10-26T00:00', allDay: true}}, now) > 0, true);
console.log('PASS important-item lifecycle, cross-day calendar coverage, inclusive dates and local timezone');
